# Core verifier pipeline
# ---------------------------
def verify_prescription(presc_text: str, current_medications_text: str, allergies_text: str,
                        patient_name: str, patient_dob: str, patient_mrn: str,
                        prescriber_name: str, prescriber_license: str, prescriber_dea: str) -> Dict:
    """
    Main orchestration function that returns a structured verification report.
    """
    try:
        # 1) Extract fields from free-form prescription if provided
        extracted = extract_prescription_structured(presc_text)
        # Use explicit fields if provided (prefer explicit over extracted)
        # Build medication list from extraction + current_medications_text
        meds = []
        if extracted.get("data", {}).get("medications"):
            meds.extend(extracted["data"]["medications"])
        # Also parse current_medications_text lines
        for line in current_medications_text.splitlines():
            line = line.strip()
            if not line:
                continue
            # basic parse: first token(s) as name
            dose = ""
            m = re.search(r'([0-9]+(?:\.[0-9]+)?\s*(?:mg|g|mcg|ml|units))', line, re.I)
            if m:
                dose = m.group(1)
            meds.append({"name": line.split()[0:2] and " ".join(line.split()[:2]) or line, "dose_text": dose, "raw": line})

        med_names = [m.get("name","").strip() for m in meds if m.get("name")]
        # 2) Drug validation via RxNav
        drug_validations = []
        rxcuis = []
        for m in meds:
            name = m.get("name", "")
            if not name:
                continue
            rx = rxnorm_search(name)
            if rx.get("rxcui"):
                rxcui = rx["rxcui"]
                rxcuis.append(rxcui)
                props = rx.get("properties", {})
                brand = props.get("brandName") or props.get("synonym") or props.get("name")
                generic = props.get("genericName") or props.get("name")
                drug_validations.append({
                    "input_name": name,
                    "found_rxcui": rxcui,
                    "brand": brand,
                    "generic": generic,
                    "rxnav_properties": props
                })
            else:
                drug_validations.append({"input_name": name, "found_rxcui": None, "candidates": rx.get("candidates", [])})

        # 3) Dosage checks (simple)
        dosage_checks = []
        for m in meds:
            name = m.get("name", "")
            dv, du = parse_dosage(m.get("dose_text", ""))
            dosage_checks.append({
                "med_name": name,
                "dose_text": m.get("dose_text"),
                "parsed_value": dv,
                "parsed_unit": du,
                "dosage_check_result": check_dosage_range(name, dv, du)
            })

        # 4) Interaction checks via rxcuis
        interactions = rxnav_interactions(list(set([r for r in rxcuis if r])))
        # 5) Allergy checks
        allergies = [a.strip() for a in allergies_text.split(",") if a.strip()]
        allergy_alerts = allergy_check(allergies, med_names)

        # 6) Prescription completeness and prescriber checks
        completeness = {}
        completeness["patient_name_ok"] = bool(patient_name or extracted.get("data",{}).get("patient_name"))
        completeness["dob_ok"] = bool(patient_dob or extracted.get("data",{}).get("dob"))
        completeness["mrn_ok"] = bool(patient_mrn or extracted.get("data",{}).get("medical_record_number"))
        completeness["prescriber_name_ok"] = bool(prescriber_name or extracted.get("data",{}).get("prescriber_name"))
        lic_ok, lic_msg = validate_license_format(prescriber_license or extracted.get("data",{}).get("prescriber_license",""))
        dea_ok, dea_msg = validate_dea_number(prescriber_dea or extracted.get("data",{}).get("prescriber_dea",""))
        completeness["prescriber_license_ok"] = lic_ok
        completeness["prescriber_license_msg"] = lic_msg
        completeness["prescriber_dea_ok"] = dea_ok
        completeness["prescriber_dea_msg"] = dea_msg

        # 7) Medicine verification summary (cross-checks)
        med_summary = []
        for dv in drug_validations:
            r = {"input_name": dv.get("input_name")}
            if dv.get("found_rxcui"):
                r["verified"] = True
                r["rxcui"] = dv.get("found_rxcui")
                r["brand"] = dv.get("brand")
                r["generic"] = dv.get("generic")
            else:
                r["verified"] = False
                r["candidates"] = dv.get("candidates", [])
            med_summary.append(r)

        # Build final report
        report = {
            "extraction_source": extracted.get("source"),
            "extracted_data": extracted.get("data"),
            "medication_validations": med_summary,
            "dosage_checks": dosage_checks,
            "interactions_found": interactions,
            "allergy_alerts": allergy_alerts,
            "completeness": completeness,
        }

        return {"success": True, "report": report}
    except Exception as e:
        return {"success": False, "error": str(e), "trace": traceback.format_exc()}

