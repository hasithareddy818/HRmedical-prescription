# NLP Extraction: either use HF model or fallback rules
# ---------------------------
def extract_prescription_structured(prescription_text: str) -> Dict:
    """
    Attempts to extract: patient name, DOB, MRN, prescriber name, DEA/license, list of medications with dosage.
    Uses HF model if available; otherwise uses regex-based fallback.
    """
    # Try HF model first
    prompt = (
        "You are a medical-prescription parser. Extract structured fields from the given prescription text.\n\n"
        "Fields to extract as JSON:\n"
        "patient_name, dob (YYYY-MM-DD if possible), medical_record_number, prescriber_name, prescriber_license, prescriber_dea, medications: [ {name, dose_text, frequency, route} ]\n\n"
        "Prescription text:\n\"\"\"\n" + prescription_text + "\n\"\"\"\n\nReturn ONLY valid JSON."
    )
    used_hf, out = hf_generate(prompt)
    if used_hf:
        # try to parse JSON in output
        try:
            # some models may preface with explanation, so find first '{'
            start = out.find('{')
            if start != -1:
                candidate = out[start:]
                data = json.loads(candidate)
                return {"source": "hf", "data": data}
        except Exception:
            # fall through to fallback parsing
            pass

    # Fallback deterministic parsing
    data = {
        "patient_name": None,
        "dob": None,
        "medical_record_number": None,
        "prescriber_name": None,
        "prescriber_license": None,
        "prescriber_dea": None,
        "medications": []
    }
    text = prescription_text

    # Simple heuristics
    # patient name: look for "Patient:" or "Name:" lines
    m = re.search(r'Patient[:\-]?\s*([A-Za-z\s.-]+?)(?:, DOB|, *MRN|\n|$)', text, re.I)
    if m:
        data["patient_name"] = m.group(1).strip()

    # DOB
    m = re.search(r'DOB[:\-]?\s*(\d{4}-\d{2}-\d{2}|\d{1,2}[/\-]\d{1,2}[/\-]\d{2,4})', text, re.I)
    if m:
        data["dob"] = m.group(1)

    # MRN / medical record
    m = re.search(r'(MRN|Medical Record #|Record #)[:\-]?\s*([A-Za-z0-9\-]+)', text, re.I)
    if m:
        data["medical_record_number"] = m.group(2)

    # Prescriber name / license / DEA
    m = re.search(r'(?:Prescriber|Provider|Dr\.|Physician)[:\-]?\s*([A-Za-z\s.-]+?)(?:, License|, *DEA|\n|$)', text, re.I)
    if m:
        data["prescriber_name"] = m.group(1).strip()
    m = re.search(r'(License|Lic#|License #)[:\-]?\s*([A-Za-z0-9\-]+)', text, re.I)
    if m:
        data["prescriber_license"] = m.group(2).strip()
    m = re.search(r'(DEA[:\-]?\s*|DEA #[:\-]?\s*)([A-Za-z0-9\-]+)', text, re.I)
    if m:
        data["prescriber_dea"] = m.group(2).strip()

    # Extract medication lines (rudimentary: lines starting with drug name or bullet)
    meds = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        # a med line often contains mg, tablet, cap, qd, BID, etc.
        if re.search(r'\b(mg|tablet|tab|cap|capsule|ml|mcg|puffs|spray|drop|qd|bid|tid|q\d+h)\b', line, re.I):
            # try to split to name and rest
            parts = re.split(r'[\-–—:]', line, maxsplit=1)
            if len(parts) == 2:
                name_part, rest = parts[0].strip(), parts[1].strip()
            else:
                # use first few words as name heuristics
                toks = line.split()
                name_part = " ".join(toks[:2])
                rest = " ".join(toks[2:])
            # Clean medication name by removing leading numbers (e.g., '1. Ibuprofen')
            name_part = re.sub(r'^\d+\.\s*', '', name_part).strip()
            # extract dosage text
            dose_match = re.search(r'([0-9]+(?:\.[0-9]+)?\s*(?:mg|g|mcg|μg|ml|units))', line, re.I)
            dose_text = dose_match.group(1) if dose_match else ""
            meds.append({"name": name_part, "dose_text": dose_text, "raw": line})
    data["medications"] = meds
    return {"source": "fallback", "data": data}

