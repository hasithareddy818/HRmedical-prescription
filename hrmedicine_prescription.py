def safe_json(response):
    try:
        return response.json()
    except Exception:
        return {}

# 1) RxNorm search to get RxCUI and names
def rxnorm_search(drug_name: str) -> Dict:
    url = f"{RXNAV_BASE}/rxcui.json"
    params = {"name": drug_name}
    try:
        resp = requests.get(url, params=params, timeout=10)
        data = safe_json(resp)
        rxcui = data.get("idGroup", {}).get("rxnormId", [])
        if rxcui:
            rxcui = rxcui[0]
            # get properties
            prop = requests.get(f"{RXNAV_BASE}/rxcui/{rxcui}/properties.json", timeout=10).json()
            return {"rxcui": rxcui, "properties": prop.get("properties", {})}
        else:
            # try approximate search
            resp2 = requests.get(f"{RXNAV_BASE}/approximateTerm.json", params={"term": drug_name}, timeout=10)
            data2 = safe_json(resp2)
            candidates = data2.get("approximateGroup", {}).get("candidate", [])
            return {"rxcui": None, "candidates": candidates}
    except Exception as e:
        return {"error": str(e)}

# 2) Get interactions via RxNav interaction API
def rxnav_interactions(rxcuis: List[str]) -> List[Dict]:
    # Accepts list of RxCUIs, returns interactions if any
    results = []
    if not rxcuis:
        return results
    try:
        rxcui_param = "+".join(rxcuis)
        url = f"{RXNAV_BASE}/interaction/list.json"
        params = {"rxcuis": rxcui_param}
        resp = requests.get(url, params=params, timeout=15)
        data = safe_json(resp)
        interaction_group = data.get("interactionTypeGroup", [])
        for group in interaction_group:
            for itype in group.get("interactionType", []):
                for interaction in itype.get("interactionPair", []):
                    results.append({
                        "interactionConcept": interaction.get("interactionConcept", []),
                        "description": interaction.get("description"),
                        "severity": interaction.get("severity"),
                        "contraindication": interaction.get("contraindication"),
                    })
    except Exception as e:
        results.append({"error": str(e)})
    return results

# 3) Get drug label info (openFDA or RxNav concept) - we keep it simple using RxNav properties
def get_drug_details_by_rxcui(rxcui: str) -> Dict:
    try:
        resp = requests.get(f"{RXNAV_BASE}/rxcui/{rxcui}/allProperties.json", params={"prop": "all"}, timeout=10)
        return safe_json(resp)
    except Exception as e:
        return {"error": str(e)}

# 4) Simple dosage parser (extract number and unit)
def parse_dosage(dosage_text: str) -> Tuple[Optional[float], Optional[str]]:
    if not dosage_text:
        return None, None
    m = re.search(r'([0-9]+(?:\.[0-9]+)?)\s*(mg|g|mcg|μg|ml|units)?', dosage_text, re.I)
    if m:
        val = float(m.group(1))
        unit = m.group(2).lower() if m.group(2) else None
        # normalize microgram
        if unit == "μg":
            unit = "mcg"
        return val, unit
    return None, None

# 5) Simple dosage check against example ranges
def check_dosage_range(drug_name: str, dose_val: Optional[float], dose_unit: Optional[str]) -> str:
    if not dose_val:
        return "No dosage provided to check."
    dn = drug_name.lower()
    # try to find simple match
    for k in EXAMPLE_DOSAGE_RANGES:
        if k in dn or dn in k:
            info = EXAMPLE_DOSAGE_RANGES[k]
            expected_unit = info["unit"]
            if dose_unit and dose_unit != expected_unit:
                return f"Unit mismatch: provided {dose_unit}, expected {expected_unit} for {k} (approx)."
            if dose_val < info["min"]:
                return f"Dosage {dose_val}{expected_unit} is below typical lower bound ({info['min']}{expected_unit}) for {k}."
            if dose_val > info["max"]:
                return f"Dosage {dose_val}{expected_unit} is above typical upper bound ({info['max']}{expected_unit}) for {k}."
            return f"Dosage {dose_val}{expected_unit} is within example range ({info['min']}-{info['max']}{expected_unit})."
    return "No local dosage ranges found for this medication (use authoritative clinical database in production)."

# 6) Allergy check - rudimentary: check given allergy keywords against drug name and known synonyms (from RxNav properties)
def allergy_check(allergies: List[str], drug_names: List[str]) -> List[str]:
    alerts = []
    lower_drugs = " ".join(drug_names).lower()
    for a in allergies:
        if not a:
            continue
        if a.lower() in lower_drugs:
            alerts.append(f"Allergy match: patient allergic to '{a}', appears in medication list.")
    return alerts

# 7) Basic prescriber license validators (format checks)
def validate_license_format(license_text: str) -> Tuple[bool, str]:
    if not license_text:
        return False, "No license number provided."
    # Very permissive check: between 4 and 20 alnum chars
    if re.match(r'^[A-Za-z0-9\-\s]{4,20}$', license_text):
        return True, "Format looks OK (not authoritative)."
    return False, "License number format looks invalid."

# 8) DEA number validation (US DEA number checksum algorithm)
def validate_dea_number(dea: str) -> Tuple[bool, str]:
    if not dea:
        return False, "No DEA number provided."
    dea = dea.replace('-', '').upper()
    if len(dea) != 9:
        return False, "DEA must be 9 characters (e.g., AB1234563)."
    if not re.match(r'^[A-Z][A-Z]\d{7}$', dea):
        return False, "DEA format invalid (expected 2 letters followed by 7 digits)."
    try:
        digits = dea[2:]
        # checksum algorithm:
        # 1) Sum of 1st,3rd,5th digits
        # 2) Sum of 2nd,4th,6th digits *2
        # 3) Add together and last digit should equal 7th digit (check digit)
        nums = [int(d) for d in digits]
        s1 = nums[0] + nums[2] + nums[4]
        s2 = (nums[1] + nums[3] + nums[5]) * 2
        check = (s1 + s2) % 10
        if check == nums[6]:
            return True, "DEA number appears valid (checksum OK)."
        else:
            return False, "DEA checksum failed."
    except Exception as e:
        return False, f"DEA validation error: {e}"

