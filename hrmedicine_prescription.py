def hf_generate(prompt: str, max_length=512, temperature=0.0) -> Tuple[bool, str]:
    """
    Attempt to call Hugging Face Inference API with HF_TOKEN and model HF_MODEL_ID.
    Returns (used_hf:boolean, output_text).
    If HF_TOKEN not set or call fails, returns (False, message).
    """
    if not HF_TOKEN:
        return False, "HF_TOKEN not set; using fallback parsing."
    try:
        from huggingface_hub import InferenceApi
        inference = InferenceApi(repo_id=HF_MODEL_ID, token=HF_TOKEN)
        # For instruction style models, sending prompt as input
        resp = inference(prompt, params={"max_new_tokens": 512, "temperature": temperature})
        # inference may return dict or string
        if isinstance(resp, dict) and 'generated_text' in resp:
            return True, resp['generated_text']
        if isinstance(resp, str):
            return True, resp
        # otherwise try to serialize
        return True, str(resp)
    except Exception as e:
        return False, f"Hugging Face inference failed: {e}"

